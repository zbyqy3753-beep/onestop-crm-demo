export type Track = "cellular" | "home";

/** התקרה שהמחשבון מוכן להתייחס אליה כחשבון חודשי אמיתי. */
export const MAX_SPEND = 5000;

/**
 * עלייה במחיר שהוצהרה **בטקסט השיווקי בלבד**.
 *
 * ⚠️ זה החור שנשאר אחרי `hasKnownAfterPrice`. אותה פונקציה פוסלת רק
 * חבילה שמילאה `priceAfterPromoNote` והשאירה את המספר ריק — 11
 * חבילות. אבל 56 מתוך 90 החבילות החודשיות משאירות את **שני** השדות
 * ריקים, והמחשבון התייחס אליהן כאילו המחיר שלהן קבוע לנצח רק מפני
 * שאיש לא מילא שדה. זה תגמל בדיוק את מי שקבר את העלייה עמוק יותר:
 *
 *  • Partner Golden 5G — 39.9 ₪, שני השדות ריקים, ובתיאור:
 *    "מחיר התכנית מהחודש ה-13 והלאה- 59.9 ₪". עלייה של 50%.
 *  • גולן "חודשיים ראשונים 24.90" — 34.9 ₪, "מחיר מובטח ל-12 חודשים".
 *  • HOT "סיב 1G ב109" — "מחודש 4".
 *
 * לכן הטקסט **פוסל** את החבילה, ולא מנסה לגזור ממנו מחיר. פירסור
 * הנוסח החופשי הוא בדיוק הניחוש שהמחשבון נבנה כדי למנוע (יש בו
 * "+ 10 ₪ נתב" שצריך חיבור ו-"מ-100 ₪" שהוא רצפה); "לא יודעים —
 * לא מבטיחים" הוא התשובה היחידה שאפשר לעמוד מאחוריה.
 */
const RISE_IN_TEXT =
  // ⚠️ "תקף ל 24 חודשים" (גולן Valentine's), "קבוע ל24 חודשים" (פלאפון
  // 1000GB) ו-"למשך שנתיים" / "למשך 5 שנים" (HOT RUS / ULTRA) הן אותה
  // הצהרה בדיוק כמו "מובטח ל-12 חודשים" — מחיר שנגמר בתאריך, ואחריו
  // לא נמסר כלום. הן לא נבחרות היום כי WeCom זולה יותר, אבל ברגע
  // שהיא תצא מהקטלוג "מחיר קבוע ל-24 חודשים" הופך לכותרת של "לנצח".
  //
  // ⚠️ סריקה מול הקטלוג (12.9.2026) מצאה שש צורות נוספות של אותה הצהרה
  // שהרגקס לא תפס: `אח"כ 49.9` (HOT), `חודשיים ראשונים` (יו"ד כפולה —
  // הגרסה הקודמת תפסה רק "חודשים"), `לחודשיים ראשונים` (פרטנר Fiber),
  // `חודש ראשון חינם` (סטינג), `ואז 179 שח` (בזק) ו-`לאחר שנה 159 ₪`
  // (סלקום טריפל WiFi — ל-`לאחר` היו רק "מכן"/"תום"). כולן מסוננות היום
  // מסיבה אחרת או שה-`price` שלהן הוא כבר המחיר הרגיל, ולכן הבחירות לא
  // משתנות — אבל ברענון הבא כל אחת מהן היא כותרת "לנצח" על מחיר של
  // חודשיים.
  /לאחר מכן|לאחר שנה|לאחר \d+ חודשים|אח"כ|אח״כ|אחר כך|ואז \d|מהחודש ה|מחודש \d|החודשים הראשונים|חודשי?ים ראשונים|לחודשיים|חודש ראשון|שנה שניי?ה|שנה שלישית|שנה רביעית|למשך שנה|למשך שנתיים|למשך \d+ שנים|מובטח ל[-־]?\s?\d+|תקף ל[-־]?\s?\d+|קבוע ל[-־]?\s?\d+|לתקופה של \d+|בתום ה?(תקופה|הטבה|המבצע|השנה)|לאחר תום|מחיר לאחר|מחיר רגיל/;

export function declaresRiseInText(p: Package): boolean {
  return RISE_IN_TEXT.test(`${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שהמחיר שלה מותנה בכמות קווים שהמבקר לא בהכרח קונה.
 *
 * ⚠️ המשך ישיר של `price > 0`: אותו דפוס בדיוק, רק שהפעם המחיר נרשם
 * כמספר אמיתי במקום 0, ולכן חמק. גולן "4 ב 130 *2*" רשומה 32 ₪ — וזה
 * המחיר **לקו השני בחבילה של ארבעה** ("עלות החבילה לכל קו שני
 * ₪32.00"), לא מחיר של קו בודד. HOT "TOTAL 5G 300GB" פותחת ב-"*לרוכשים
 * 2 מנויים ויותר*", כלומר מינימום חוזי.
 *
 * היום אף אחת מהן אינה נבחרת (WeCom ב-29.9 ₪ מנצחת בכל כמות), ולכן זו
 * הגנה על **הרענון הבא** ולא תיקון של מספר שמוצג כרגע: ברגע שהזולה
 * ביותר תצא מהקטלוג, "32 ₪ לקו שני בחבילת ארבעה" הופך לכותרת של מי
 * שביקש קו אחד.
 *
 * ⚠️ נבדק גם מול `name`, ולא רק מול הטקסט: ל-"4 ב 130 *2*" אין
 * `description` כלל, והשם הוא הראיה היחידה שקיימת.
 */
const REQUIRES_MULTIPLE_LINES =
  // ⚠️ `ב[-־ ]?` ולא `ב\s?`: "3 קווים ב-99" עם מקף הוא אותו תמחור בדיוק
  // כמו "3 קווים ב99", והגרסה הקודמת תפסה רק את השנייה.
  /לרוכשים \d+ מנויים|קו שני|\*\s?[2-9]\s?\*|\d+\s?קווים ב[-־\s]?\s?\d/;

export function requiresMultipleLines(p: Package): boolean {
  return REQUIRES_MULTIPLE_LINES.test(`${p.name} ${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שהמחיר שלה הוא מחיר **למנוי במסלול משפחתי** — כלומר משני
 * קווים ומעלה — בלי שהקטלוג אומר זאת במספרים.
 *
 * ⚠️ WeCom מוכרת את אותה חבילה בדיוק פעמיים: "wecomFree 4G" ב-34.9 ₪
 * ו-"wecomFamily 4G (מסלול משפחתי)" ב-29.9 ₪. אותם 10,000GB, אותן
 * 5,000 דקות, אותו eSIM; ההבדל היחיד הוא המילה "משפחתי" — ובמחירון
 * של WeCom "משפחתי" פירושו מנוי מ-2 מנויים. `lineTiers` ריק ואין
 * `priceAfterPromo`, ולכן שום מסנן לא תפס את זה, ומי שביקש **קו אחד**
 * קיבל כותרת שנבנתה על 29.9 במקום 34.9 — ₪60 בשנה שלא יראה.
 *
 * זו לא פסילה גורפת כמו `requiresMultipleLines`: לשני קווים ומעלה
 * המחיר המשפחתי הוא בדיוק המחיר שיגבו, ולכן הבדיקה תלוית-כמות ויושבת
 * ב-`computeSaving` לצד `priceUnknownAtLines`.
 */
const FAMILY_ONLY = /מסלול משפחתי|משפחתי/;

export function familyPriceOnly(p: Package): boolean {
  return FAMILY_ONLY.test(`${p.name} ${p.description ?? ""}`);
}

/**
 * חבילה שהצהירה על עלייה **וגם** על תמחור לפי כמות מנויים — כלומר המחיר
 * שאחרי ההטבה תלוי בכמות, ו-`priceAfterPromo` הוא מספר אחד בלבד.
 *
 * ⚠️ `perLinePrice` מתעלמת ממדרגות ברגע שיש מחיר-אחרי-הטבה, כי המדרגות
 * מתומחרות על בסיס ההטבה. זה נכון — אבל הוא מניח שהמספר היחיד שנמסר
 * הוא המחיר לכל כמות, וסלקום "משפחתי פלוס" מפריכה את זה בטקסט שלה
 * עצמה: `priceAfterPromo` הוא 59.9, והתיאור אומר "לאחר שנה … עד 2
 * מנויים כולל – 64.90 ₪ למנוי". מי שביקש קו אחד היה מקבל 59.9 —
 * ₪60 בשנה שלא יראה. היא לא נבחרת היום (WeCom זולה יותר), ולכן זו
 * הגנה על הרענון הבא.
 *
 * הכלל אינו פירסור של המחיר מהטקסט אלא אותו "לא יודעים — לא מבטיחים":
 * כשהטקסט אומר שהמחיר משתנה לפי כמות והמספרים לא מפרטים לפי כמות,
 * המחיר לכמות המבוקשת פשוט לא נמסר.
 */
const PRICED_BY_LINE_COUNT = /מנויים כולל|מנויים ומעלה|קווים ומעלה|בהצטרפות \d+ מנויים|בצירוף \d+ קווים/;

export function afterPriceDependsOnLines(p: Package): boolean {
  if (p.priceModel !== "monthly" || p.priceAfterPromo == null) return false;
  return PRICED_BY_LINE_COUNT.test(`${p.name} ${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילת בית שהנתב שלה מתומחר **בנפרד** מהמחיר שנרשם.
 *
 * ⚠️ yes "אולטימייט + אינטרנט": `price` 209, `priceAfterPromo` 229, ובטקסט
 * "עלות נתב אינטרנט 20שח (יש הטבה על הנתב למשך שנה ללא עלות)". כלומר
 * מהשנה השנייה החשבון הוא 249 ולא 229 — ו-`hasKnownAfterPrice` עבר,
 * כי המספר שנמסר הוא מחיר החבילה בלי הציוד. פרטנר Fiber 600: "נתב
 * פייבר בהשכרה בתוספת 25 ₪ לחודש" על מחיר של 100.
 *
 * "עלות נתב 0 ש"ח" ו-"נתב כלול במחיר" אינם נתפסים — הספרה חייבת להיות
 * שונה מאפס, ו"כלול" אינו "בתוספת". חבילות שכבר סכמו את הנתב לתוך
 * המחיר ("139 ₪ + 34.9 ₪ נתב = 173.9 ₪") אינן נפסלות בגלל השורה הזו.
 */
const ROUTER_PRICED_SEPARATELY = /הטבה על הנתב|נתב[^.•]{0,25}?בתוספת|עלות נתב\D{0,15}[1-9]\d*\s?(?:₪|שח|ש"ח)/;

export function routerPricedSeparately(p: Package): boolean {
  return ROUTER_PRICED_SEPARATELY.test(`${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שכוללת תוספת (חבילת ערוצים, HBO) שניתנת **חינם לתקופה ואחר כך
 * מחויבת** — חיוב חודשי שמחיר-אחרי-ההטבה לא מכיל.
 *
 * ⚠️ זה החור שנשאר אחרי `routerPricedSeparately`, רק לתוכן במקום
 * לציוד. HOT "סיב 1000/100 כולל NEXT TV" — הבחירה של מסלול הבית —
 * רשומה 119 → 135, ובטקסט: "12 ערוצי דרמות חינם אח"כ 49.9" ו-"2חודשים
 * HBO אח"כ 25שח". `RISE_IN_TEXT` היה תופס את `אח"כ`, אבל `isComparable`
 * מדלג עליו ברגע שיש `priceAfterPromo` מספרי — כי הניחה שהמספר הזה
 * הוא כל החשבון. כאן הוא לא: מהחודש הרביעי החשבון הוא 135 ועוד 74.9
 * על תוכן שנכנס לחבילה בחינם, וכותרת של "₪115 בחודש" נבנתה על המספר
 * הקטן.
 *
 * הנוסח מכוון: "חינם אח"כ N" / "ללא עלות ואח"כ N". "חודשיים ב-59 אח"כ
 * 119" (המחיר עצמו עולה) אינו נתפס — לזה יש `priceAfterPromo`.
 */
const ADDON_FREE_THEN_PAID = /(?:חינם|ללא עלות|במתנה)\s*ו?אח["״]?כ\s?\d|חודש(?:ים|יים)\s+[^\n\d]{2,30}?\s?אח["״]?כ\s?\d/;

export function addonFreeThenPaid(p: Package): boolean {
  return ADDON_FREE_THEN_PAID.test(`${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שהמבקר במסלול הזה באמת יכול לעבור אליה.
 *
 * ⚠️ הפילטר הזה הוא מה שמפריד בין "עד כמה אפשר לחסוך" לבין מספר
 * מומצא. בלעדיו הזולה ביותר ב-`home` היא **קו טלפון של בזק ל-50 דקות**
 * (19.9 ₪) — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת של ₪2,401
 * חיסכון מול מוצר שאינו אינטרנט ואינו טלוויזיה. באותו אופן 6 מתוך 8
 * החבילות הזולות בסלולר הן כשר או DATA ONLY, שאינן תחליף לקו רגיל.
 *
 * `price > 0` נבדק כאן ולא נשען על `listable()` של הקורא: בקטלוג יש
 * חבילות שמתומחרות לחבילה שלמה (`3 קווים ב99`) ורשומות כ-0, ומחיר 0
 * מייצר "חיסכון" של מלוא החשבון.
 */
export function isComparable(p: Package, track: Track): p is MonthlyPackage {
  if (p.category !== track || p.priceModel !== "monthly") return false;
  // ⚠️ `typeof` ולא `== null` — ראה `isListable`: הקטלוג נכנס דרך cast
  // בלי ולידציה, ומחיר שיישאב פעם אחת כמחרוזת עובר כל השוואה מספרית
  // ב-JS ומגיע לכותרת כ-NaN.
  if (typeof p.price !== "number" || !Number.isFinite(p.price) || p.price <= 0) return false;
  if (p.editorial?.hidden) return false;
  // ⚠️ חבילה שהעלייה שלה מוצהרת בטקסט חופשי בלבד אינה בת-השוואה כאן:
  // המחיר היחיד שאפשר לחשב ממנה הוא מחיר ההטבה, והכותרת מבטיחה את
  // ההפך. ראה `hasKnownAfterPrice` ו-`declaresRiseInText`.
  if (!hasKnownAfterPrice(p)) return false;
  if (p.priceAfterPromo == null && declaresRiseInText(p)) return false;
  // ⚠️ מחיר שמותנה בכמות קווים אינו מחיר שהמבקר הזה יקבל. ראה
  // `requiresMultipleLines`.
  if (requiresMultipleLines(p)) return false;
  // ⚠️ מחיר-אחרי-הטבה אחד לחבילה שמצהירה על מחיר לפי כמות. ראה
  // `afterPriceDependsOnLines`.
  if (afterPriceDependsOnLines(p)) return false;
  // ⚠️ תוכן (או שירות) שנכנס בחינם ומתחיל להיות מחויב הוא חיוב חודשי שמחיר-אחרי-
  // ההטבה לא מכיל. ראה `addonFreeThenPaid`.
  if (addonFreeThenPaid(p)) return false;

  if (track === "cellular") {
    const spec = p.spec as CellularSpec;
    return !spec.kosher && (spec.unlimitedData || (spec.dataGb ?? 0) > 0) && (spec.minutes ?? 0) >= 1000;
  }
  /*
   * ⚠️ **גם אינטרנט וגם טלוויזיה**, ולא `hasInternet` לבדו.
   *
   * המסלול מציג את עצמו כ"אינטרנט וטלוויזיה" והמבקר מזין את החשבון
   * החודשי **הכולל** שלו. מתוך 25 חבילות הבית שעברו את הפילטר 13 הן
   * אינטרנט בלבד — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת חיסכון
   * מול חבילה שאין בה טלוויזיה, והפער הזה הוא לא הנחה אלא שירות
   * שנעלם. התנאי הקודם חסם בדיוק את הכיוון ההפוך (TV בלבד) והשאיר
   * את זה פתוח.
   *
   * קו הטלפון עדיין אינו נדרש — הוא מוזכר בהסתייגות שמתחת למספר.
   *
   * ⚠️ `type !== "TV"` הוא **תיקון לנתון שגוי במקור**, לא הידור נוסף.
   * סטינג "החבילה המושלמת" רשומה `hasInternet: true` למרות שהיא שירות
   * סטרימינג בלבד ("שירות טלוויזיה הפועל על גבי האינטרנט") — המחלץ
   * קרא את המילה "אינטרנט" בתיאור. היא הזולה בקטגוריה, כלומר בלי
   * השורה הזו היא הופכת לחבילה שמולה נמדד כל חשבון טריפל בארץ.
   */
  // ⚠️ נתב שמתומחר מחוץ למחיר הוא חיוב חודשי שהכותרת לא רואה. ראה
  // `routerPricedSeparately`.
  if (routerPricedSeparately(p)) return false;
  const spec = p.spec as HomeSpec;
  return spec.hasInternet && spec.hasTv && p.type !== "TV";
}

/**
 * המחיר לקו **שנשאר אחרי שההטבה נגמרת**.
 *
 * ⚠️ זה הלב של התיקון. `price` לבדו הוא מחיר ההטבה: HOT Synergy עולה
 * 21.9 ₪ והופך ל-57.9 ₪ בתום שנה — פי 2.64. כותרת שנתית שנבנתה על
 * 21.9 מנפחת את החיסכון פי 3.3, וגרוע מכך היא סותרת את ההבטחה של
 * הדף עצמו ("כולל המחיר אחרי תום ההטבה"). `afterPrice` כבר מחזירה את
 * המחיר הקבוע, וזה המספר היחיד שאפשר לעמוד מאחוריו לשנה שלמה.
 *
 * מדרגות הקווים מתומחרות על בסיס ההטבה, ולכן הן נלקחות בחשבון רק
 * כשהחבילה לא הצהירה על עלייה — אחרת היינו מערבבים מחיר מבצע לקו עם
 * מחיר קבוע ומקבלים סכום שאינו נכון באף נקודת זמן. (סלקום "משפחתי
 * פלוס" היא המקרה: 39.9 היום, 59.9 אחר כך, ומדרגות שמתומחרות מול
 * 39.9. 59.9 לכל כמות הוא המספר השמרני, ולכן הנבחר.)
 */
export function perLinePrice(p: MonthlyPackage, lines: number): number {
  const base = afterPrice(p);
  if (p.priceAfterPromo != null) return base;
  const tiers = (p.spec as CellularSpec).lineTiers;
  if (!tiers?.length) return base;
  const tier = tiers.filter((t) => t.lines <= lines).sort((a, b) => b.lines - a.lines)[0];
  /*
   * ⚠️ `tier.price` כפי שהוא, ובלי `Math.min` מול המחיר הבסיסי.
   *
   * מדרגה היא המחיר שהמפעיל גובה בכמות הזו — לפעמים **גבוה** מהמחיר
   * המוצג. גולן "קיץ חם בדור 5" מוצגת ב-39.9 אבל דורשת 44.9 ₪ לקו
   * בשני קווים; `Math.min` החזיר 39.9 והציג לזוג חיסכון גדול ב-₪120
   * בשנה ממה שיקבלו בפועל.
   */
  return tier ? tier.price : base;
}

/**
 * כמות קווים שהמחיר בה **אינו ידוע**, למרות שיש מחיר רשום.
 *
 * ⚠️ ההנחה ש-`price` הוא תמיד המחיר לקו בודד אינה נכונה. גולן "קיץ חם
 * בדור 5" רשומה 39.9 ₪ — וזה מחיר **שלושה** קווים; התיאור מפרט "קו
 * בודד – 49.90 ₪, 2 קווים – 44.90 ₪ לקו, 3 קווים ומעלה – 39.90 ₪ לקו",
 * ו-`lineTiers` מתחיל ב-2. מי שביקש קו אחד קיבל 39.9 (נפילה ל-`base`
 * בהיעדר מדרגה מתאימה), כלומר כותרת מנופחת ב-₪120 בשנה מול מה שיגבו
 * ממנו בפועל — אותו סוג טעות ש-`Math.min` יצר לכיוון השני, רק שהפעם
 * היא נובעת מ**היעדר** מדרגה ולא ממדרגה שגויה.
 *
 * הזיהוי אינו פירסור של הטקסט אלא סתירה פנימית בנתונים עצמם: טבלת
 * מדרגות רק **מוזילה** ככל שמוסיפים קווים, ולכן מחיר בסיס **נמוך**
 * מהמדרגה בכמות הקטנה ביותר שהוצהרה אינו יכול להיות המחיר בכמות
 * קטנה עוד יותר. במצב כזה המחיר לכמות המבוקשת פשוט לא נמסר, ו"לא
 * יודעים — לא מבטיחים" הוא אותו כלל שכבר חל על עליות מחיר.
 *
 * Partner Star (39.9 בסיס, מדרגות מ-3 קווים ב-33) וסלקום 5G PRO
 * (59.9 בסיס, מדרגה 2 ב-59.9) עקביות ולכן נשארות.
 */
export function priceUnknownAtLines(p: MonthlyPackage, lines: number): boolean {
  // מחיר-אחרי-הטבה מדווח גובר על המדרגות בכל כמות. ראה `perLinePrice`.
  if (p.priceAfterPromo != null) return false;
  const tiers = (p.spec as CellularSpec).lineTiers;
  if (!tiers?.length) return false;
  if (tiers.some((t) => t.lines <= lines)) return false;
  const smallest = [...tiers].sort((a, b) => a.lines - b.lines)[0];
  return afterPrice(p) < smallest.price;
}

export interface Saving {
  /** החבילה שנבחרה, או `null` כשאין בקטגוריה חבילה בת-השוואה. */
  pick: MonthlyPackage | null;
  monthly: number;
  yearly: number;
  /** יש חבילה, והיא באמת זולה מהחשבון הנוכחי. */
  worthwhile: boolean;
}

/**
 * ⚠️ מעוגל פעם אחת, והשנה נגזרת ממנו.
 *
 * חבילה במחיר 29.9 ₪ כפול שלושה קווים מייצרת "חיסכון של ₪1,563.6
 * בשנה" — והאגורות האלה הן בדיוק מה שגורם למספר להיראות מומצא.
 * חשוב מזה: עיגול נפרד לחודש ולשנה הציג שני מספרים שסותרים זה את זה
 * על אותו מסך (₪154 בחודש לצד ₪1,852 בשנה, כשהמכפלה היא 1,848).
 * לכן מעגלים את החודש ומכפילים — שתי השורות תמיד מסתדרות.
 */
export function computeSaving(
  packages: Package[],
  track: Track,
  units: number,
  monthlySpend: number,
): Saving {
  const pool = packages
    .filter((p): p is MonthlyPackage => isComparable(p, track))
    // ⚠️ תלוי-כמות, ולכן כאן ולא ב-`isComparable`. ראה `priceUnknownAtLines`.
    .filter((p) => !priceUnknownAtLines(p, units))
    // ⚠️ מחיר "משפחתי" הוא מחיר לשני קווים ומעלה. ראה `familyPriceOnly`.
    .filter((p) => track !== "cellular" || units >= 2 || !familyPriceOnly(p));
  const pick = pool.reduce<MonthlyPackage | null>(
    (best, p) => (best == null || perLinePrice(p, units) < perLinePrice(best, units) ? p : best),
    null,
  );
  if (!pick) return { pick: null, monthly: 0, yearly: 0, worthwhile: false };

  // Cellular is priced per line; a home package is one household bill.
  const perLine = perLinePrice(pick, units);
  const newMonthly = track === "cellular" ? perLine * units : perLine;
  const monthly = Math.round(monthlySpend - newMonthly);
  return { pick, monthly, yearly: monthly * 12, worthwhile: monthlySpend > 0 && monthly > 0 };
}

/**
 * הסכום החודשי הנמוך ביותר שהמחשבון מוכן להתייחס אליו כחשבון אמיתי.
 *
 * ⚠️ `> 0` לבדו הכניס את `0.5` למסך: הכפתור נדלק, המחשבון הצהיר "אתם
 * כבר משלמים מעט יחסית", והנציג קיבל בהערה "משלם היום ₪0.5 בחודש".
 * החבילה הזולה בקטלוג היא 19.9 ₪, ולכן חשבון חד-ספרתי אינו סכום שנפל
 * בו קו אחד — הוא קלט שגוי, וצריך להיראות כך.
 */
export const MIN_SPEND = 10;

/**
 * הפורמט **השלם** של סכום שהמחשבון מקבל.
 *
 * ⚠️ זה התיקון לשורש של כל משפחת הבאגים הזו: הגרסה הקודמת **ניקתה**
 * את המחרוזת (`replace(/[^\d.]/g, "")`) ורק אחר כך חיפשה חריגות, ולכן
 * כל שומר נכתב בנפרד וכל אחד פספס משהו אחר. כאן המחרוזת כולה חייבת
 * להתאים לתבנית אחת, ומה שלא תואם נפסל — בלי "הצלה" שקטה:
 *
 *  • `1.200` — הכתיב האירופאי לאלף ומאתיים. השומר הקודם נכתב לפסיק
 *    בלבד ("יותר מנקודה אחת"), ולכן נקודה **בודדת** חמקה: הקלט הפך
 *    בשקט ל-1.2, המסך הצהיר "אתם משלמים ₪1.2 בחודש", והנציג קיבל את
 *    אותו מספר בהערה. זה בדיוק התרחיש של `220,5`, רק בכיוון ההפוך.
 *    לכן החלק העשרוני מוגבל לשתי ספרות — לחשבון חודשי אין שלוש.
 *  • `2 20` — רווח באמצע. `\s` היה ברשימת המותרים ונמחק בניקוי, כלומר
 *    טעות הקלדה של רווח אחד הכפילה סדר גודל. רווח מותר רק בקצוות.
 *
 * `1,200`, `₪ 1,200`, `1,200.50`, `220.5` ו-`0050` ממשיכים לעבוד.
 */
const AMOUNT = /^₪?\s*(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d{1,2})?\s*₪?$/;

/**
 * קריאת הסכום שהמבקר הקליד.
 *
 * ⚠️ `\d` בלי הדגל `u` לא תופס ספרות ערביות-הודיות, ומקלדת ערבית בנייד
 * הייתה מרוקנת את המחרוזת ומשאירה את הכפתור מושבת בלי הסבר. לכן
 * הספרות מנורמלות ל-ASCII לפני הבדיקה.
 */
export function parseSpend(raw: string): number {
  const ascii = raw
    .replace(/[٠-٩۰-۹]/g, (d) => String((d.codePointAt(0)! - 0x0660) % 16))
    // אותה מקלדת מפיקה גם מפריד עשרוני `٫` ומפריד אלפים `٬` — בלי
    // השורה הזו `٢٢٠٫٥` נפסל בעוד שההודעה מציעה "220.50".
    .replace(/٫/g, ".")
    .replace(/٬/g, ",")
    .trim();
  if (!AMOUNT.test(ascii)) return 0;
  const value = Number(ascii.replace(/[^\d.]/g, ""));
  if (!Number.isFinite(value) || value < MIN_SPEND) return 0;
  return Math.min(value, MAX_SPEND);
}
